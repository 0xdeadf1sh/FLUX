#pragma once

#include <vulkan/vulkan_raii.hpp>
#include <GLFW/glfw3.h>

namespace flux
{
    ///////////////////////////////////////////////////////////////////////////
    //////////////////////////// GLFW RAII WRAPPER ////////////////////////////
    ///////////////////////////////////////////////////////////////////////////
    struct Window
    {
        ///////////////////////////////////////////////////////////////////////////
        ////////////////////////////// WINDOW HANDLE //////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        GLFWwindow* m_window{};

        ///////////////////////////////////////////////////////////////////////////
        ///////////////////////////////// DTOR ////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        ~Window()
        {
            if (m_window)
            {
                glfwDestroyWindow(m_window);
                glfwTerminate();
            }
        }
    };
}
