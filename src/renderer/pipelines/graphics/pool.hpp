#pragma once

#include "common.hpp"
#include "../../buffer.hpp"
#include <vk_mem_alloc_enums.hpp>

namespace flux::pipelines::graphics
{
    ///////////////////////////////////////////////////////////////////////////
    class pool
    {
    public:
        ///////////////////////////////////////////////////////////////////////////
        //////////////////////// UNIFORM BUFFER TYPE ALIAS ////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        using ubo_float_type = vk_buffer<float,
                                         vk::BufferUsageFlagBits::eUniformBuffer,
                                         vma::AllocationCreateFlagBits::eHostAccessSequentialWrite>;

        ///////////////////////////////////////////////////////////////////////////
        //////////////////////////////// CTOR/DTOR ////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        pool()                                  {}
        ~pool()                                 {}

        ///////////////////////////////////////////////////////////////////////////
        /////////////////////////////// DELETED COPY //////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        pool(const pool&)                       = delete;
        pool& operator=(const pool&)            = delete;

        ///////////////////////////////////////////////////////////////////////////
        ////////////////////////////// DEFAULTED MOVE /////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        pool(pool&&)                            = default;
        pool& operator=(pool&&)                 = default;

        ///////////////////////////////////////////////////////////////////////////
        ////////////////////////////// INITIALIZATION /////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        void init(const vk::raii::Device&,
                  const vk::PipelineRenderingCreateInfo&,
                  const vk::raii::DescriptorPool&,
                  const std::vector<std::reference_wrapper<ubo_float_type>>&,
                  uint32_t);

        ///////////////////////////////////////////////////////////////////////////
        ///////////////////////////////// BINDING /////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////
        void bind(name, const vk::raii::CommandBuffer&) const;
        void bind(name, const vk::raii::CommandBuffer&, uint32_t) const;

    private:
        ///////////////////////////////////////////////////////////////////////////
        //////////////////////// POOL OF GRAPHICS PIPELINES ///////////////////////
        ///////////////////////////////////////////////////////////////////////////
        std::vector<std::unique_ptr<common>> m_pipelines{};
    };
}
